// Encode the listed PNG assets without changing their decoded sRGB pixels.
// Existing responsive/optimized variants and original downloads stay intact.
import { createRequire } from 'node:module'
import { readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { homedir } from 'node:os'
import { join } from 'node:path'
const require = createRequire(import.meta.url)
let sharp
try { sharp = require('sharp') } catch {
  sharp = require(join(homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp'))
}
const paths = [
  'assets/case-study/assets-hub/gallery.png',
  'assets/case-study/assets-hub/search.png',
  'assets/case-study/assets-hub/inspector.png',
  'assets/case-study/assets-hub/settings.png',
  'assets/serial-deminer/16-kp3Djjey5.png',
  'assets/serial-deminer/13-zIT2xV17Q.png',
  'assets/myfridge/wireframes-red.png',
  'assets/serial-deminer/15-bK7P1H_1k.png',
  'assets/serial-deminer/01-iPBd_9mAN.png',
  'assets/serial-deminer/02-we8S3oXEt.png',
  'assets/serial-deminer/14-ouluH8FSt.png',
]
// Keep gameplay PNGs with browser-specific gamma handling and the transparent
// butter logo in their original formats. Raw decoder equality alone did not
// preserve Chrome's color-managed / premultiplied canvas pixels for those.
const results = []
for (const source of paths) {
  const input = await readFile(join('public', source))
  const metadata = await sharp(input).metadata()
  if (metadata.hasProfile || metadata.orientation || metadata.space !== 'srgb') {
    console.log(`Preserving original color-managed asset: ${source}`)
    continue
  }
  const encoded = await sharp(input).webp({ lossless: true, effort: 6 }).toBuffer()
  const before = await sharp(input).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  const after = await sharp(encoded).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  if (JSON.stringify(before.info) !== JSON.stringify(after.info) || !before.data.equals(after.data)) {
    throw new Error(`Decoded pixels differ: ${source}`)
  }
  if (encoded.length >= input.length) continue
  const optimized = source.replace(/\.png$/, '.lossless.webp')
  await writeFile(join('public', optimized), encoded)
  results.push({ source, optimized, before: input.length, after: encoded.length,
    width: metadata.width, height: metadata.height,
    pixelSha256: createHash('sha256').update(before.data).digest('hex') })
  console.log(`${source}: ${input.length} -> ${encoded.length}, identical RGBA`)
}
await writeFile('src/lossless-image-pairs.js', `// Generated by scripts/optimize-lossless-images.mjs; original files remain fallback sources.\nexport const losslessImagePairs = ${JSON.stringify(results.map(({ source, optimized }) => [source, optimized]), null, 2)}\n`)
await writeFile('reference/lossless-image-verification.json', JSON.stringify(results, null, 2) + '\n')
console.log(`Saved ${results.reduce((sum, r) => sum + r.before - r.after, 0)} bytes across ${results.length} images`)
